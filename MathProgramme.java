package Javabasics;

public class MathProgramme 
{
	public static void main(String[] args)
	{
		System.out.println(Math.addExact(45, 56));
		System.out.println(Math.subtractExact(455, 90));
		
		System.out.println(Math.multiplyExact(14, 5));
		System.out.println(Math.max(45, 1000));
		
		System.out.println(Math.min(415, 3000));
		System.out.println(Math.sqrt(400));
		System.out.println(Math.random());
		
		double area=Math.PI*10*10;
		System.out.println(area);
	}

}
