package Javabasics;

public class IfElseProgramme2 
{
	public static void main(String[] args)
	{
		int a=10;
		int b=20;
		
		if(a==b)
		{
			System.out.println("Person can vote");
		}
		else if(a>b)
		{
			System.out.println("Person can not vote");
		}
		else 
		{
			System.out.println("Person can not vote");
		}
	}

}
